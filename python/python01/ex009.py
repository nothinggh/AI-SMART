#사칙연산 함수로 구하는 코드를 파이썬에서 작성해 봅시다.
# plus(a,b)
# minus()
#multiple()
#divide()

def plus(a, b):
    return a+b

print('+ :', plus(200,100))

def minus(a, b):
    return a-b

print('- :', minus(200,100))

def multiple(a, b):
    return a*b

print('* :', multiple(7,5))

def divide(a, b):
    return a/b

print('/ :', divide(7,5))